#!/usr/bin/env node
/**
 * Compile the C++ documentation samples against the real HORUS headers.
 *
 * Why this exists
 * ---------------
 * `verify:rust` compiles Rust samples and `verify:python` syntax-checks Python
 * ones, but the 233 C++ fences had nothing at all behind them — no compiler ever
 * saw them. That is the binding with the least margin for error: the C++ API is
 * a hand-written mirror of a Rust core, so a renamed field or a withdrawn type
 * shows up here as a doc that stops compiling and nowhere else.
 *
 * What it checks
 * --------------
 * Every ```cpp fence that is not flagged `partial` or `has-markers`, is not a
 * bare signature listing, and does not include a header the reader is expected
 * to write themselves. Each is compiled with `-fsyntax-only` against
 * `horus_cpp/include`, under whichever of three shapes fits:
 *
 *   1. as written (blocks that already have `int main`)
 *   2. as file-scope items, with a `main` appended
 *   3. as statements, wrapped in a function body
 *
 * A block passes if any shape compiles. This is deliberately lenient about
 * *shape* and strict about *names*: the point is to catch `horus::msg::CmdVel`
 * spelled `msg::CmdVel`, or a method that no longer exists, not to insist every
 * fence is a whole program.
 *
 * Blocks are skipped, with a reason, when the sample includes a header the
 * tutorial tells the reader to create (`demo/msgs.hpp`), a vendor SDK, or a
 * message type generated by `horus msg` and therefore absent until they run it.
 *
 * Run: node scripts/verify-cpp-local.mjs [--horus-path ../horus] [--verbose]
 * Exit status is 1 when something does not compile, so CI can gate on it.
 */

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

function args() {
  const out = { horusPath: '../horus', filter: null, verbose: false };
  for (let i = 2; i < process.argv.length; i += 1) {
    if (process.argv[i] === '--horus-path') out.horusPath = process.argv[++i];
    else if (process.argv[i] === '--filter') out.filter = new RegExp(process.argv[++i]);
    else if (process.argv[i] === '--verbose') out.verbose = true;
    else throw new Error(`Unknown argument: ${process.argv[i]}`);
  }
  return out;
}

const options = args();
const root = process.cwd();
const includeDir = path.resolve(root, options.horusPath, 'horus_cpp', 'include');
if (!fs.existsSync(path.join(includeDir, 'horus', 'horus.hpp'))) {
  console.error(`HORUS C++ headers not found at ${includeDir}`);
  process.exit(2);
}

const extractedPath = path.join(root, 'extracted-code-blocks.json');
if (!fs.existsSync(extractedPath)) {
  console.error('extracted-code-blocks.json is missing. Run `npm run extract:code` first.');
  process.exit(1);
}
const extracted = JSON.parse(fs.readFileSync(extractedPath, 'utf8'));

/**
 * A fence that is only declarations — an API reference listing a signature.
 *
 * Judged on the joined text, not line by line, because a signature is routinely
 * spread over several lines and only the last of them ends in `;`:
 *
 *     template<typename T>
 *     T get(const char* key, T default_val) const;
 *
 *     TensorHandle alloc(
 *         const TensorPool& pool,   // pool to allocate from
 *         Dtype dtype
 *     );
 *
 * A declaration has no body and no initialiser, so "no `{`, no `=`, ends in `;`"
 * separates it from real code — `auto pool = horus::TensorPool(...);` has the
 * `=` and is checked normally.
 */
function isSignatureListing(code) {
  const joined = code
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .split('\n')
    .map((l) => l.replace(/\/\/.*$/, '').trim())
    .filter(Boolean)
    .join(' ')
    .trim();
  if (!joined) return false;
  if (!joined.endsWith(';') || joined.includes('{')) return false;
  if (/[^=!<>]=[^=]/.test(joined)) return false;
  // `operator""_hz` is a declaration whose name contains an empty string
  // literal; drop it before looking for literals.
  const bare = joined.replace(/operator""/g, 'operator_');
  // A declaration names parameter types. A statement passes values and chains
  // calls, so a string literal, a numeric argument or a `.`/`->` call means
  // this is code being executed, not an API listing.
  if (/"/.test(bare)) return false;
  if (/[.]\s*[A-Za-z_]\w*\s*\(|->\s*[A-Za-z_]\w*\s*\(/.test(bare)) return false;
  if (/\(\s*[-\d]|,\s*[-\d]/.test(bare)) return false;
  return true;
}

/**
 * Headers the reader writes or generates, so the sample cannot compile here.
 * Returns the offending include, or null.
 */
function unresolvableInclude(code) {
  for (const m of code.matchAll(/#include\s*[<"]([^>"]+)[>"]/g)) {
    const h = m[1];
    if (h.startsWith('horus/')) {
      if (!fs.existsSync(path.join(includeDir, h))) return h;
      continue;
    }
    // Anything with a directory component that is not a HORUS header is either
    // the reader's own file or a third-party SDK.
    if (h.includes('/') && !h.startsWith('bits/')) return h;
  }
  return null;
}

/**
 * True when a block failed only because it continues an earlier one.
 *
 * An API page shows `sched.advertise<...>("odom")` under a heading, having built
 * `sched` three fences up. Compiled alone that is "'sched' was not declared in
 * this scope" — which says nothing about whether the documented call is right.
 * The distinction that matters: an undeclared *local* is missing context, while
 * an unknown member, a wrong type or a bad namespace is a defect in the sample.
 *
 * So: if every root error is an undeclared identifier that the block never
 * declares and that is not a `horus` name, this is a continuation. Anything else
 * — including an undeclared identifier under `horus::` — is a real failure.
 * Returns the identifiers, or null.
 */
function contextOnly(output, code) {
  const roots = output
    .split('\n')
    .filter((l) => l.includes('error:'))
    .map((l) => l.slice(l.indexOf('error:') + 6).trim());
  if (!roots.length) return null;

  const names = new Set();
  for (const e of roots) {
    // Cascades from an undeclared name on the same line carry no information.
    if (/^expected primary-expression before/.test(e)) continue;
    if (/^expected [';,)]/.test(e)) continue;
    const m = /^[‘'"]([A-Za-z_][A-Za-z0-9_]*)[’'"] (?:was not declared in this scope|does not name a type)/.exec(e);
    if (!m) return null;
    const name = m[1];
    // A horus name that does not resolve is exactly what this check is for.
    if (new RegExp(`horus::(?:\\w+::)*${name}\\b`).test(code)) return null;
    if (new RegExp(`\\b(?:class|struct|enum)\\s+${name}\\b`).test(code)) return null;
    names.add(name);
  }
  return names.size ? [...names].join(', ') : null;
}

/** Types produced by `horus msg` codegen — absent until the reader runs it. */
const GENERATED_TYPES = /\bhorus::msg::(WeatherData|SensorPacket)\b/;

const blocks = extracted.blocks.filter(
  (b) =>
    b.language === 'cpp' &&
    !b.flags.includes('partial') &&
    !b.flags.includes('has-markers') &&
    (!options.filter || options.filter.test(b.id))
);

const work = fs.mkdtempSync(path.join(os.tmpdir(), 'horus-docs-cpp-'));
const failures = [];
let checked = 0;
const skipped = [];

// Precompile the HORUS headers once.
//
// Every block otherwise re-parses ~5,000 lines of horus_cpp/include, which is
// 1.3s of the ~1.5s each compile takes. With the header precompiled it is 0.3s,
// and the job goes from about ten minutes to about two -- the difference between
// a check CI keeps and one someone turns off. Forced in with `-include`, so it
// also covers blocks that write their own #include lines: the include guards
// make those a no-op.
const preludeHeader = path.join(work, 'horus_docs_prelude.hpp');
fs.writeFileSync(preludeHeader, '#include <horus/horus.hpp>\n#include <horus/messages.hpp>\n');
const pch = spawnSync(
  process.env.CXX || 'g++',
  ['-std=c++17', '-w', '-I', includeDir, '-x', 'c++-header', preludeHeader, '-o', preludeHeader + '.gch'],
  { encoding: 'utf8' }
);
// A failed precompile is not fatal -- it only costs speed -- but it usually
// means the headers themselves stopped compiling, which is worth saying.
const usePch = pch.status === 0;
if (!usePch) {
  // Say why. A silent fallback turns a broken header into "the job got slower",
  // and the reason is usually worth reading: no disk for the ~90 MB .gch, or the
  // headers themselves no longer compiling.
  const why = `${pch.stdout || ''}${pch.stderr || ''}`.trim().split('\n').slice(0, 4).join('\n');
  console.error(
    'note: could not precompile the HORUS headers; falling back to per-block ' +
      `parsing, which is roughly 4x slower${why ? `:\n${why}` : ` (g++ exited ${pch.status})`}`
  );
}

function compile(file) {
  const flags = ['-std=c++17', '-fsyntax-only', '-w'];
  if (usePch) flags.push('-include', preludeHeader, '-I', work);
  flags.push('-I', includeDir, file);
  return spawnSync(process.env.CXX || 'g++', flags, { encoding: 'utf8' });
}

try {
  for (let i = 0; i < blocks.length; i += 1) {
    const block = blocks[i];
    const code = block.code;

    if (isSignatureListing(code)) {
      skipped.push(`${block.id} — signature listing`);
      continue;
    }
    const bad = unresolvableInclude(code);
    if (bad) {
      skipped.push(`${block.id} — includes ${bad}, which the reader supplies`);
      continue;
    }
    if (GENERATED_TYPES.test(code)) {
      skipped.push(`${block.id} — uses a type generated by \`horus msg\``);
      continue;
    }

    // `using namespace horus::literals;` is the prerequisite the duration page
    // states once, at the top of its Literals section, and the samples below it
    // rely on. Supplying it here matches what a reader following the page has in
    // scope; without it every `50_hz` is an "unable to find numeric literal
    // operator" that says nothing about the doc.
    const needsLiterals = /\b\d+_(?:hz|s|ms|us|ns)\b/.test(code) && !/using namespace horus::literals/.test(code);
    const prelude =
      (usePch || code.includes('#include')
        ? ''
        : '#include <horus/horus.hpp>\n#include <horus/messages.hpp>\n') +
      (needsLiterals ? 'using namespace horus::literals;\n' : '');
    const hasMain = /\bint\s+main\s*\(/.test(code);
    const shapes = hasMain
      ? [prelude + code]
      : [
          prelude + code + '\n',
          `${prelude}int __horus_docs_body() {\n${code}\nreturn 0;\n}\n`,
        ];

    checked += 1;
    let passed = false;
    const outputs = [];
    for (let s = 0; s < shapes.length; s += 1) {
      const file = path.join(work, `block_${i}_${s}.cpp`);
      fs.writeFileSync(file, shapes[s]);
      const result = compile(file);
      if (result.status === 0) {
        passed = true;
        break;
      }
      outputs.push(`${result.stdout}${result.stderr}`.trim());
    }
    if (!passed) {
      // Ask every shape, not just the last one. A member-function body fails the
      // statement wrapper with "a function-definition is not allowed here" — a
      // fact about the wrapper — while the file-scope shape fails with the
      // undeclared members that actually explain it. Judging on the last output
      // alone reported that block as a defect.
      const missing = outputs.map((o) => contextOnly(o, code)).find(Boolean);
      if (missing) {
        skipped.push(`${block.id} — continues an earlier block (uses ${missing})`);
        checked -= 1;
        continue;
      }
      // Report the attempt that got furthest: fewest errors.
      const lastOutput = outputs
        .slice()
        .sort((a, b) => (a.match(/error:/g) || []).length - (b.match(/error:/g) || []).length)[0] || '';
      failures.push({ block, output: lastOutput });
      console.error(`FAIL ${block.id}`);
      if (options.verbose) console.error(lastOutput.split('\n').slice(0, 6).join('\n'));
    } else if (options.verbose) {
      console.log(`PASS ${block.id}`);
    }
  }
} finally {
  fs.rmSync(work, { recursive: true, force: true });
}

if (options.verbose && skipped.length) {
  console.log(`\nSkipped ${skipped.length} block(s):`);
  for (const s of skipped) console.log(`  ${s}`);
}

// A pass that examined nothing is not a pass.
if (checked < 100) {
  console.error(`only ${checked} C++ blocks examined — the selection is broken`);
  process.exit(2);
}

console.log(
  `C++ documentation verification: ${checked - failures.length}/${checked} passed` +
    ` (${skipped.length} skipped as unbuildable by design)`
);
if (failures.length) process.exit(1);
